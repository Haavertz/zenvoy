vim.opt.runtimepath:prepend(vim.fn.getcwd())
local t = dofile("tests/helpers.lua")
local attachments = require("zenvoy.core.attachments")

local root = vim.fn.tempname() .. "-zenvoy-attachments"
vim.fn.mkdir(root .. "/dir with space", "p")
local file = root .. "/dir with space/report, final.pdf"
vim.fn.writefile({ "12345" }, file)

t.test("resolves typed, quoted, relative, home and file URL paths", function()
   local resolved = assert(attachments.resolve("  " .. file .. "  "))
   t.equal(file, resolved.path)
   t.equal("report, final.pdf", resolved.name)
   t.equal(6, resolved.size)
   t.equal(file, assert(attachments.resolve('"' .. file .. '"')).path)
   t.equal(file, assert(attachments.resolve("'" .. file .. "'")).path)
   t.equal(file, assert(attachments.resolve(vim.uri_from_fname(file))).path)
   local cwd = vim.fn.getcwd()
   vim.cmd.cd(vim.fn.fnameescape(root))
   local relative = attachments.resolve("dir with space/report, final.pdf")
   vim.cmd.cd(vim.fn.fnameescape(cwd))
   t.equal(file, relative and relative.path)
   local home = vim.env.HOME
   vim.env.HOME = root
   t.equal(file, assert(attachments.resolve("~/dir with space/report, final.pdf")).path)
   t.equal(file, assert(attachments.resolve("$HOME/dir with space/report, final.pdf")).path)
   vim.env.HOME = home
end)

t.test("reports missing files, directories, blank lines and multiline input", function()
   t.equal(nil, (attachments.resolve("   ")))
   t.equal(nil, select(2, attachments.resolve("   ")))
   assert(select(2, attachments.resolve(root .. "/missing.pdf")):find("not found", 1, true))
   assert(select(2, attachments.resolve(root)):find("not a file", 1, true))
   assert(select(2, attachments.resolve(file .. "\n/etc/passwd")):find("single line", 1, true))
end)

t.test("parses every line, skips blanks and duplicates, and stops at the first error", function()
   local files = assert(attachments.parse({ file, "", file, "  " }))
   t.equal(1, #files)
   local result, err = attachments.parse({ file, root .. "/nope" })
   t.equal(nil, result)
   assert(err:find("nope", 1, true))
   t.equal({}, attachments.parse({ "" }))
end)

t.test("formats sizes and type labels", function()
   t.equal("13 B", attachments.format_size(13))
   t.equal("1.5 KB", attachments.format_size(1536))
   t.equal("48 KB", attachments.format_size(49152))
   t.equal("1.2 MB", attachments.format_size(1258291))
   t.equal(nil, attachments.format_size(nil))
   t.equal("PDF", attachments.kind("relatório.pdf", "application/pdf"))
   t.equal("OCTET-STREAM", attachments.kind(nil, "application/octet-stream"))
   t.equal("MS-SPREADSH…", attachments.kind("data", "application/vnd.ms-spreadsheetml-long"))
   t.equal("FILE", attachments.kind(nil, nil))
end)

t.test("neutralizes spoofing characters in names and flags executable types", function()
   t.equal("invoicefdp.exe", attachments.display_name("invoice\226\128\174fdp.exe"))
   t.equal("a b", attachments.display_name("a\nb"))
   t.equal("fallback", attachments.display_name("\226\128\139", "fallback"))
   t.equal(true, attachments.is_executable("setup.EXE"))
   t.equal(true, attachments.is_executable("run.sh"))
   t.equal(false, attachments.is_executable("photo.png"))
   t.equal(false, attachments.is_executable(nil))
end)

assert(root:match("zenvoy%-attachments$"))
vim.fn.delete(root, "rf")
t.finish("attachments_spec")
